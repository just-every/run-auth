import assert from 'node:assert/strict';
import {openLink} from './link/runtime.mjs';
import {AUTH_ORIGIN,APP_ORIGIN,APP_SETUP_TOKEN} from './link/origins.mjs';
import {emailSession,cookieOf} from './runtime.mjs';
import {passkeyPerson} from './agents-helpers.mjs';
import {authenticate} from './webauthn.mjs';
import {fixtureEmail,command,grant,people,operations,identityState} from './session-control-helpers.mjs';

export async function nativeSessionControl(t) {
 const r=await openLink();t.after(()=>r.close());
 const owner=await passkeyPerson(r,'owner',['owner','example.com'].join('@'),'owner');
 const employee=await passkeyPerson(r,'employee',fixtureEmail(2));
 const second=await emailSession(r,fixtureEmail(2));
 const desk=await passkeyPerson(r,'desk',fixtureEmail(3));
 await grant(r,owner.cookie,'desk','help-desk',['employee']);
 await grant(r,owner.cookie,'employee','employee',['employee'],[]);
 await r.call('/.well-known/openid-configuration');
 await r.db.prepare('UPDATE auth_signing_keys SET use_after=?').bind(r.now-1).run();
 const linked=await command(r,owner.cookie,'/api/auth/apps/link-token',{origin:APP_ORIGIN},201);
 assert.equal((await r.send(APP_ORIGIN+'/auth/dependencies/setup',{method:'POST',json:{issuer:AUTH_ORIGIN,interface:'oidc-provider@1',token:APP_SETUP_TOKEN}})).status,200);
 assert.equal((await r.send(APP_ORIGIN+'/auth/bootstrap',{method:'POST',json:{token:APP_SETUP_TOKEN,displayName:'Owner'}})).status,303);
 assert.equal((await r.send(AUTH_ORIGIN+'/oidc/link/initiate',{method:'POST',json:{origin:APP_ORIGIN,interface:'oidc-provider@1',token:linked.token},cookies:false})).status,200);
 assert.equal((await r.send(APP_ORIGIN+'/auth/invite',{method:'POST',json:{email:fixtureEmail(2),displayName:'Employee'}})).status,202,'the app owner admits the employee through its own invitation door');
 r.jar[APP_ORIGIN].clear();r.jar[AUTH_ORIGIN].set(...employee.cookie.split('='));
 const signedIn=await r.follow(APP_ORIGIN+'/auth/oidc/auth/start',{method:'POST',json:{returnTo:'/'}});
 assert.ok(signedIn.status<400,await signedIn.clone().text());
 const appSession=await r.send(APP_ORIGIN+'/auth/session');assert.equal(appSession.status,200);
 assert.equal((await appSession.json()).operator.email,fixtureEmail(2));
 for(const cookie of [employee.cookie,second])assert.equal((await r.call('/api/auth/me',{cookie})).status,200);
 const view=await people(r,desk.cookie);assert.equal(view.find(p=>p.id==='employee').canEndSessions,true);
 const before=await identityState(r,'employee');
 const result=await command(r,desk.cookie,'/api/auth/roles/end-sessions',{personId:'employee',reason:'Employee reported a misplaced shared laptop'});
 assert.equal(result.ok,true);assert.ok(result.operationId);assert.ok(result.nativeSessionsEnded>=2);
 assert.equal(result.refreshGrantsEnded,0);
 for(const cookie of [employee.cookie,second])assert.equal((await r.call('/api/auth/me',{cookie})).status,401,'the next Auth request refuses every ended browser');
 assert.equal((await r.send(APP_ORIGIN+'/auth/session')).status,401,'the real linked Base app refuses its previous session');
 assert.deepEqual(await identityState(r,'employee'),before,'ending sessions preserves identity, passkeys and grants');
 assert.equal((await r.call('/api/auth/me',{cookie:owner.cookie})).status,200);
 const receipt=(await operations(r,desk.cookie,'employee')).find(op=>op.id===result.operationId);
 assert.equal(receipt.actorId,'desk');assert.equal(receipt.reason,'Employee reported a misplaced shared laptop');
 assert.equal(receipt.nativeSessionsEnded,result.nativeSessionsEnded);assert.ok(receipt.createdAt);
 assert.equal(receipt.logout.delivered,1,'the operation reports the native logout acknowledgment');
 await r.db.prepare('DELETE FROM auth_logout_deliveries WHERE id LIKE ? AND finished_at IS NOT NULL').bind(result.operationId+':%').run();
 assert.deepEqual((await operations(r,desk.cookie,'employee')).find(op=>op.id===result.operationId).logout,receipt.logout,'the linked-app receipt retains terminal counts independently of its transient queue');
 const audit=await (await r.call('/api/auth/roles/audit',{cookie:owner.cookie})).json();
 assert.ok(audit.events.some(event=>event.actor_id==='desk'&&event.subject_id==='employee'&&JSON.parse(event.detail??'{}').reason===receipt.reason),'the public audit records the accountable actor and their reason');
 const resumed=await authenticate(r,employee.key);assert.equal(resumed.response.status,200,await resumed.response.clone().text());
 const me=await r.call('/api/auth/me',{cookie:cookieOf(resumed.response)});assert.equal(me.status,200);
 r.jar[APP_ORIGIN].clear();r.jar[AUTH_ORIGIN].set(...cookieOf(resumed.response).split('='));
 assert.ok((await r.follow(APP_ORIGIN+'/auth/oidc/auth/start',{method:'POST',json:{returnTo:'/'}})).status<400);
 assert.equal((await r.send(APP_ORIGIN+'/auth/session')).status,200,'the employee can sign in to the same app again');
}
